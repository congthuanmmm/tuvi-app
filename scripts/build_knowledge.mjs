// Bundles the Ziwei skill's interpretation references into a TS module for the AI prompt.
// Usage: node scripts/build_knowledge.mjs <path-to-Numerologist_skills/ziwei-doushu>
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2];
if (!src) throw new Error("missing path to ziwei-doushu");
const skill = readFileSync(join(src, "SKILL.md"), "utf8");
const rules = skill.slice(skill.indexOf("## 核心规则"), skill.indexOf("## 工作流程"));
const reading = skill.slice(skill.indexOf("### 第四步"), skill.indexOf("## 结尾提醒"));
const refs = ["stars.md", "sihua.md", "patterns.md"].map((f) => readFileSync(join(src, "references", f), "utf8"));
const knowledge = [rules, reading, ...refs].join("\n\n");
writeFileSync(
  "src/lib/ai/knowledge.ts",
  `// Generated by scripts/build_knowledge.mjs from FANzR-arch/Numerologist_skills. Do not edit.\nexport const ZIWEI_KNOWLEDGE = ${JSON.stringify(knowledge)};\n`,
);
console.log(`knowledge: ${knowledge.length} chars`);
