// Tách tài liệu Tử Vi của Numerologist_skills và bài Wiki thành dữ liệu có cấu trúc cho prompt AI.
// Dùng: node scripts/build_knowledge.mjs <path-to-Numerologist_skills/ziwei-doushu>
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const src = process.argv[2];
if (!src) throw new Error("missing path to ziwei-doushu");
const read = (f) => readFileSync(join(src, f), "utf8");
const between = (s, a, b) => {
  const i = s.indexOf(a);
  if (i < 0) throw new Error(`missing ${a}`);
  const j = b ? s.indexOf(b, i + a.length) : -1;
  return s.slice(i, j < 0 ? undefined : j).trim();
};
const rows = (md) =>
  md.split("\n").filter((l) => /^\|/.test(l) && !/^\|[\s-|]+\|$/.test(l))
    .map((l) => l.split("|").slice(1, -1).map((c) => c.trim()));

const skill = read("SKILL.md");
const rules = [between(skill, "## 核心规则", "## 工作流程"), between(skill, "### 第四步", "## 结尾提醒")].join("\n\n");

const stars = read("references/stars.md");
const majorStars = {};
for (const m of between(stars, "## 主星详解", "## 主星组合").matchAll(/^### (\S+?)星\n([\s\S]*?)(?=^### |^---)/gm)) {
  majorStars[m[1]] = m[2].trim();
}
const minorStars = {};
for (const sec of [between(stars, "## 辅星详解", "## 六煞星"), between(stars, "## 六煞星", "## 庙旺陷表")]) {
  for (const [name, wx, trait, ming] of rows(sec)) {
    if (name === "星名") continue;
    minorStars[name] = `五行${wx}；核心特质：${trait}；在命宫：${ming}`;
  }
}
const majorTable = Object.fromEntries(rows(between(stars, "## 主星总览", "## 主星详解"))
  .filter((r) => r[0] !== "星名").map(([n, wx, yy, kw, role]) => [n, `五行${wx}，${yy}；关键词：${kw}；类比：${role}`]));
for (const k of Object.keys(majorStars)) majorStars[k] = `${majorTable[k] ?? ""}\n${majorStars[k]}`;
const brightness = between(stars, "### 庙旺陷的实际影响");
const extra = {
  luma: between(stars, "禄存+天马", "---"),
  shaNote: between(stars, "煞星不全是凶", "---"),
};

const sihua = read("references/sihua.md");
const sihuaMeaning = Object.fromEntries(rows(between(sihua, "### 四化含义", "### 四化的层次"))
  .filter((r) => r[0] !== "四化").map(([t, , wx, core, ana]) => [t, `五行${wx}；${core}；类比：${ana}`]));
const sihuaPalace = {};
for (const t of ["化禄", "化权", "化科", "化忌"]) {
  sihuaPalace[t] = Object.fromEntries(rows(between(sihua, `### ${t}入各宫`, "###")).filter((r) => r[0] !== "宫位"));
}
const sihuaNotes = {
  principles: between(sihua, "### 重要原则", "---"),
  ji: between(sihua, "### 化忌的深层理解", "---"),
  stack: Object.fromEntries(rows(between(sihua, "**叠加效应**", "### 流年四化")).filter((r) => r[0] !== "组合")),
  luJiClash: between(sihua, "### 禄忌对冲"),
  layers: between(sihua, "### 三层四化综合分析步骤", "---"),
};

const pat = read("references/patterns.md");
const patterns = {};
for (const m of pat.matchAll(/^### \d+\. (.+)\n([\s\S]*?)(?=^### |^## )/gm)) patterns[m[1].trim()] = m[2].trim();
const patternRules = [between(pat, "## 判断要点", "## 常见吉格"), between(pat, "## 成格与破格")].join("\n\n");

const catalog = readFileSync("src/lib/wiki/catalog.ts", "utf8");
const wiki = {};
for (const [, type, body] of catalog.matchAll(/e\("([a-z-]+)", "[^"]+", \[([\s\S]*?)\]\),/g)) {
  for (const [, slug, name, han] of body.matchAll(/\["([^"]+)", "([^"]+)", "([^"]+)"\]/g)) {
    const f = `content/wiki/${type}/${slug}.json`;
    if (!existsSync(f)) continue;
    const d = JSON.parse(readFileSync(f, "utf8"));
    const sections = d.sections.map((s) => `#### ${s.heading}\n${s.body}`).join("\n\n");
    for (const h of han.split(/\s*\/\s*/)) wiki[`${type}:${h}`] = { name, summary: d.summary, sections };
  }
}

const KB = { rules, majorStars, minorStars, brightness, extra, sihuaMeaning, sihuaPalace, sihuaNotes, patterns, patternRules, wiki };
writeFileSync(
  "src/lib/ai/kb.ts",
  `// Generated by scripts/build_knowledge.mjs from FANzR-arch/Numerologist_skills and content/wiki. Do not edit.\nexport const KB = ${JSON.stringify(KB, null, 1)} as const;\n`,
);
console.log({
  majorStars: Object.keys(majorStars).length, minorStars: Object.keys(minorStars).length,
  sihuaPalace: Object.values(sihuaPalace).map((x) => Object.keys(x).length), stack: Object.keys(sihuaNotes.stack).length,
  patterns: Object.keys(patterns).length, wiki: Object.keys(wiki).length, bytes: JSON.stringify(KB).length,
});
